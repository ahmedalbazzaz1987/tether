    /// HID usage -> Mac key code (with aliases for keys Macs do not have).
    static let hidToMac: [UInt16: UInt16] = {
        var m: [UInt16: UInt16] = [:]
        for (mac, hid) in macToHID { m[hid] = mac }
        m[0x32] = 0x2A // non-US # -> backslash
        m[0x46] = 0x69 // Print Screen -> F13
        m[0x47] = 0x6B // Scroll Lock -> F14
        m[0x48] = 0x71 // Pause -> F15
        return m
    }()

