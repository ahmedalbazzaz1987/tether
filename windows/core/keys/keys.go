// Package keys maps USB HID keyboard usages to Windows set-1 scan codes / virtual keys.
package keys

// Win describes how to inject a HID usage on Windows.
// If VK != 0 the virtual key is used; otherwise Scan (with Ext = E0 prefix).
type Win struct {
	Scan uint16
	Ext  bool
	VK   uint16
}

var HIDToWin = map[uint16]Win{}

func init() {
	letters := []uint16{0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32,
		0x31, 0x18, 0x19, 0x10, 0x13, 0x1F, 0x14, 0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C}
	for i, s := range letters {
		HIDToWin[uint16(0x04+i)] = Win{Scan: s}
	}
	for i := 0; i < 10; i++ { // 1..9,0 -> 0x02..0x0B
		HIDToWin[uint16(0x1E+i)] = Win{Scan: uint16(0x02 + i)}
	}
	plain := map[uint16]uint16{
		0x28: 0x1C, 0x29: 0x01, 0x2A: 0x0E, 0x2B: 0x0F, 0x2C: 0x39, 0x2D: 0x0C, 0x2E: 0x0D,
		0x2F: 0x1A, 0x30: 0x1B, 0x31: 0x2B, 0x32: 0x2B, 0x33: 0x27, 0x34: 0x28, 0x35: 0x29,
		0x36: 0x33, 0x37: 0x34, 0x38: 0x35, 0x39: 0x3A,
		0x3A: 0x3B, 0x3B: 0x3C, 0x3C: 0x3D, 0x3D: 0x3E, 0x3E: 0x3F, 0x3F: 0x40, 0x40: 0x41,
		0x41: 0x42, 0x42: 0x43, 0x43: 0x44, 0x44: 0x57, 0x45: 0x58,
		0x47: 0x46, // scroll lock
		0x55: 0x37, 0x56: 0x4A, 0x57: 0x4E,
		0x59: 0x4F, 0x5A: 0x50, 0x5B: 0x51, 0x5C: 0x4B, 0x5D: 0x4C, 0x5E: 0x4D, 0x5F: 0x47,
		0x60: 0x48, 0x61: 0x49, 0x62: 0x52, 0x63: 0x53, 0x64: 0x56, 0x67: 0x59,
		0x68: 0x64, 0x69: 0x65, 0x6A: 0x66, 0x6B: 0x67, 0x6C: 0x68, 0x6D: 0x69, 0x6E: 0x6A,
		0x6F: 0x6B, 0x70: 0x6C, 0x71: 0x6D, 0x72: 0x6E, 0x73: 0x76,
		0xE0: 0x1D, 0xE1: 0x2A, 0xE2: 0x38, 0xE5: 0x36,
	}
	for h, s := range plain {
		HIDToWin[h] = Win{Scan: s}
	}
	ext := map[uint16]uint16{
		0x46: 0x37, 0x49: 0x52, 0x4A: 0x47, 0x4B: 0x49, 0x4C: 0x53, 0x4D: 0x4F, 0x4E: 0x51,
		0x4F: 0x4D, 0x50: 0x4B, 0x51: 0x50, 0x52: 0x48, 0x54: 0x35, 0x58: 0x1C, 0x65: 0x5D,
		0xE3: 0x5B, 0xE4: 0x1D, 0xE6: 0x38, 0xE7: 0x5C,
	}
	for h, s := range ext {
		HIDToWin[h] = Win{Scan: s, Ext: true}
	}
	vk := map[uint16]uint16{
		0x48: 0x13,                         // pause
		0x53: 0x90,                         // num lock
		0x7F: 0xAD, 0x80: 0xAF, 0x81: 0xAE, // mute, vol up, vol down
	}
	for h, v := range vk {
		HIDToWin[h] = Win{VK: v}
	}
}
